#!/usr/bin/env bash
# agent_autoupdate.sh - Optional component: a systemd user timer that updates
# merge the newest aged stable upstream Codex release into the user's local
# fork, rebuild installed Codex runtimes, and update Claude Code and Cline from
# stable npm releases published at least AGENT_AUTOUPDATE_DELAY_HOURS ago.
#
# The Codex fork is updated from stable GitHub release tags and compiled locally.
# Claude Code and Cline use npm publish timestamps. The timer fires at
# user-manager startup (the first user session after reboot) and daily.

AGENT_AUTOUPDATE_SHARE_DIR="${AGENT_AUTOUPDATE_SHARE_DIR:-$TARGET_HOME/.local/share/linux_codex_claude_code_setup}"
AGENT_AUTOUPDATE_CONFIG_DIR="${AGENT_AUTOUPDATE_CONFIG_DIR:-$TARGET_HOME/.config/linux_codex_claude_code_setup}"
AGENT_AUTOUPDATE_SCRIPT="$AGENT_AUTOUPDATE_SHARE_DIR/agent-autoupdate.sh"
AGENT_AUTOUPDATE_NPM_ATOMIC_LIB="$AGENT_AUTOUPDATE_SHARE_DIR/npm_atomic_install.sh"
AGENT_AUTOUPDATE_CODEX_FORK_LIB="$AGENT_AUTOUPDATE_SHARE_DIR/codex_fork_install.sh"
AGENT_AUTOUPDATE_SYSTEMD_DIR="$TARGET_HOME/.config/systemd/user"
AGENT_AUTOUPDATE_SERVICE="agent-autoupdate.service"
AGENT_AUTOUPDATE_TIMER="agent-autoupdate.timer"
AGENT_AUTOUPDATE_DELAY_HOURS="${AGENT_AUTOUPDATE_DELAY_HOURS:-24}"
AGENT_AUTOUPDATE_QWEN_NPM_PREFIX="${QWEN_CODEX_NPM_PREFIX:-$TARGET_HOME/.local/codex-qwen}"
AGENT_AUTOUPDATE_OPENROUTER_NPM_PREFIX="${OPENROUTER_CODEX_NPM_PREFIX:-$TARGET_HOME/.local/codex-openrouter}"
AGENT_AUTOUPDATE_NVIDIA_NPM_PREFIX="${NVIDIA_CODEX_NPM_PREFIX:-$TARGET_HOME/.local/codex-nvidia}"
AGENT_AUTOUPDATE_CODEX_FORK_DIR="${CODEX_FORK_DIR:-$TARGET_HOME/projects/codex}"
AGENT_AUTOUPDATE_CODEX_FORK_BRANCH="${CODEX_FORK_BRANCH:-main}"
AGENT_AUTOUPDATE_CODEX_UPSTREAM_URL="${CODEX_FORK_UPSTREAM_URL:-https://github.com/openai/codex.git}"
AGENT_AUTOUPDATE_CODEX_REPOSITORY_URL="${CODEX_FORK_REPOSITORY_URL:-https://github.com/mikaeltorni/codex.git}"
AGENT_AUTOUPDATE_CODEX_RELEASES_API_URL="${CODEX_FORK_RELEASES_API_URL:-https://api.github.com/repos/openai/codex/releases}"

# install_agent_autoupdate - install the updater script, its env file, and the
# user service+timer, then enable the timer. Best-effort systemctl calls so a
# headless or session-less install still records the units for the next login.
install_agent_autoupdate() {
  msg "Installing delayed agent auto-update (all Codex runtimes + Claude Code + Cline, ${AGENT_AUTOUPDATE_DELAY_HOURS}h delay)"

  run_as_target mkdir -p "$AGENT_AUTOUPDATE_SHARE_DIR" "$AGENT_AUTOUPDATE_CONFIG_DIR" "$AGENT_AUTOUPDATE_SYSTEMD_DIR"
  run_as_target cp "$SCRIPT_DIR/assets/agent-autoupdate.sh" "$AGENT_AUTOUPDATE_SCRIPT"
  run_as_target chmod +x "$AGENT_AUTOUPDATE_SCRIPT"
  # The updater sources these helpers next to itself for safe binary replacement
  # and for building the same local fork used by the CLI installers.
  run_as_target cp "$SCRIPT_DIR/assets/npm_atomic_install.sh" "$AGENT_AUTOUPDATE_NPM_ATOMIC_LIB"
  run_as_target cp "$SCRIPT_DIR/assets/codex_fork_install.sh" "$AGENT_AUTOUPDATE_CODEX_FORK_LIB"

  run_as_target tee "$AGENT_AUTOUPDATE_CONFIG_DIR/autoupdate.env" >/dev/null <<EOF
# Generated by linux_codex_claude_code_setup — sourced by agent-autoupdate.sh.
# Only releases published at least this many hours ago are installed, so a freshly
# published (possibly compromised) version is never taken on its release day.
AGENT_AUTOUPDATE_DELAY_HOURS=$AGENT_AUTOUPDATE_DELAY_HOURS
CODEX_NPM_PREFIX=$CODEX_NPM_PREFIX
QWEN_CODEX_NPM_PREFIX=$AGENT_AUTOUPDATE_QWEN_NPM_PREFIX
OPENROUTER_CODEX_NPM_PREFIX=$AGENT_AUTOUPDATE_OPENROUTER_NPM_PREFIX
NVIDIA_CODEX_NPM_PREFIX=$AGENT_AUTOUPDATE_NVIDIA_NPM_PREFIX
CODEX_FORK_DIR=$AGENT_AUTOUPDATE_CODEX_FORK_DIR
CODEX_FORK_BRANCH=$AGENT_AUTOUPDATE_CODEX_FORK_BRANCH
CODEX_FORK_UPSTREAM_URL=$AGENT_AUTOUPDATE_CODEX_UPSTREAM_URL
CODEX_FORK_REPOSITORY_URL=$AGENT_AUTOUPDATE_CODEX_REPOSITORY_URL
CODEX_FORK_RELEASES_API_URL=$AGENT_AUTOUPDATE_CODEX_RELEASES_API_URL
CLINE_NPM_PREFIX=$CLINE_NPM_PREFIX
EOF

  run_as_target tee "$AGENT_AUTOUPDATE_SYSTEMD_DIR/$AGENT_AUTOUPDATE_SERVICE" >/dev/null <<EOF
[Unit]
Description=Delayed auto-update for all Codex runtimes, Claude Code, and Cline
After=default.target
[Service]
Type=oneshot
ExecStart=$AGENT_AUTOUPDATE_SCRIPT
EOF

  run_as_target tee "$AGENT_AUTOUPDATE_SYSTEMD_DIR/$AGENT_AUTOUPDATE_TIMER" >/dev/null <<EOF
[Unit]
Description=Run delayed auto-update for all Codex runtimes, Claude Code, and Cline at user startup and daily
[Timer]
# Fire shortly after the per-user service manager starts. User managers normally
# start at the first login after a system reboot, so this is the boot-adjacent
# run supported by a user timer; the daily monotonic run is the steady-state
# fallback when the user session remains up.
OnStartupSec=2min
OnUnitActiveSec=1d
Persistent=true
[Install]
WantedBy=timers.target
EOF

  run_as_target systemctl --user daemon-reload 2>/dev/null \
    || msg "systemctl --user daemon-reload unavailable; timer enables on next login"
  run_as_target systemctl --user enable --now "$AGENT_AUTOUPDATE_TIMER" 2>/dev/null \
    || msg "Could not enable $AGENT_AUTOUPDATE_TIMER now; it activates on next login"
}

# detect_agent_autoupdate - true when the timer unit is installed for the user.
detect_agent_autoupdate() {
  [ -f "$AGENT_AUTOUPDATE_SYSTEMD_DIR/$AGENT_AUTOUPDATE_TIMER" ]
}

# uninstall_agent_autoupdate - disable and remove the timer, service, updater
# script, and env file. Leaves the installed CLIs in place.
uninstall_agent_autoupdate() {
  msg "Removing delayed agent auto-update timer and updater script"
  run_as_target systemctl --user disable --now "$AGENT_AUTOUPDATE_TIMER" 2>/dev/null || true
  run_as_target rm -f \
    "$AGENT_AUTOUPDATE_SYSTEMD_DIR/$AGENT_AUTOUPDATE_TIMER" \
    "$AGENT_AUTOUPDATE_SYSTEMD_DIR/$AGENT_AUTOUPDATE_SERVICE" \
    "$AGENT_AUTOUPDATE_SCRIPT" \
    "$AGENT_AUTOUPDATE_NPM_ATOMIC_LIB" \
    "$AGENT_AUTOUPDATE_CONFIG_DIR/autoupdate.env"
  run_as_target systemctl --user daemon-reload 2>/dev/null || true
}
